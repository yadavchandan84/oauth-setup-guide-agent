// scripts/sync-shared.mjs — copies shared/ into */src/generated (gitignored).
// Dependency-free: node:fs / node:path only. Runs as pre{dev,build,test,typecheck}.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const sharedDir = path.join(repoRoot, 'shared');
const guidesDir = path.join(sharedDir, 'guides');
const schemaSrc = path.join(sharedDir, 'schema.ts');

const targets = [
  path.join(repoRoot, 'frontend', 'src', 'generated'),
  path.join(repoRoot, 'backend', 'src', 'generated'),
];

function fail(msg) {
  console.error(msg);
  process.exit(1);
}

function assertShared(target) {
  if (!fs.existsSync(sharedDir) || !fs.existsSync(schemaSrc)) {
    fail(
      `shared/ not found next to ${target} — on Vercel enable 'Include source files outside of the Root Directory'`
    );
  }
}

// Read + validate every curated guide, returning GuideInput-shaped objects sorted by app.name.
function readGuides() {
  if (!fs.existsSync(guidesDir)) return [];
  const files = fs
    .readdirSync(guidesDir)
    .filter((f) => f.endsWith('.json'))
    .sort();
  const guides = [];
  for (const file of files) {
    const full = path.join(guidesDir, file);
    const text = fs.readFileSync(full, 'utf8');
    let parsed;
    try {
      parsed = JSON.parse(text);
    } catch (err) {
      fail(`Failed to parse ${file}: ${err?.message ?? err}`);
    }
    const stem = file.replace(/\.json$/, '');
    if (parsed?.slug !== stem) {
      fail(`Slug mismatch in ${file}: filename stem "${stem}" !== slug "${parsed?.slug}"`);
    }
    guides.push(parsed);
  }
  guides.sort((a, b) => String(a?.app?.name ?? '').localeCompare(String(b?.app?.name ?? '')));
  return guides;
}

function writeTarget(target, guides) {
  assertShared(target);
  fs.mkdirSync(target, { recursive: true });

  const schemaHeader = '// AUTO-GENERATED from shared/schema.ts — do not edit\n';
  fs.writeFileSync(path.join(target, 'schema.ts'), schemaHeader + fs.readFileSync(schemaSrc, 'utf8'));

  const literal = JSON.stringify(guides, null, 2);
  const curated =
    '// AUTO-GENERATED by scripts/sync-shared.mjs — do not edit\n' +
    "import { GuideSchema, type GuideInput, type Guide } from './schema.js';\n" +
    `const raw: GuideInput[] = ${literal};\n` +
    'export const curatedGuides: Guide[] = raw.map(g => GuideSchema.parse(g)); // applies defaults; throws on invalid\n';
  fs.writeFileSync(path.join(target, 'curatedGuides.ts'), curated);
}

const guides = readGuides();
for (const target of targets) writeTarget(target, guides);
console.log(`sync-shared: wrote schema.ts + curatedGuides.ts (${guides.length} guides) to ${targets.length} targets`);
